"""
make_numbers_tex.py -- write manuscript/numbers.tex, a file of LaTeX macros
holding every numerical value quoted from the computational outputs.

Both main.tex and SM.tex \\input this file, so no result is typed by hand.
Re-run after any re-analysis:

    python scripts/make_numbers_tex.py
"""
from __future__ import annotations

import json
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RE = ROOT / "results/tables/reanalysis/reanalysis_report.json"
EX = ROOT / "results/validation/exact_independent.json"
SIM = ROOT / "results/validation/sim_independent.json"
CB = ROOT / "results/validation/containment_bruteforce.json"
OUT = ROOT / "manuscript/numbers.tex"


def f(x, d=4, sign=True):
    s = f"{x:+.{d}f}" if sign else f"{x:.{d}f}"
    return s.replace("+", "+") if x >= 0 else s.replace("-", "-")


def sci(x, d=1):
    m, e = f"{x:.{d}e}".split("e")
    return f"{m}\\times10^{{{int(e)}}}"


def pct(x, d=1):
    return f"{100 * x:.{d}f}"


def macro(name, val):
    return f"\\newcommand{{\\{name}}}{{{val}}}\n"


def main():
    r = json.load(open(RE))
    bs = r["bootstrap"]
    pe = r["point_estimates"]
    dg = r["diagnostics"]
    P = bs["stated|strat|B2000"]
    O = bs["main_noN|orig|B500"]
    I = bs["stated|iid|B2000"]
    MC = bs["stated|mc_only|B2000"]
    SO = bs["stated|orig|B2000"]
    QC = bs["q_cat|strat|B2000"]
    CF = bs["nq_cellFE|strat|B2000"]
    MN = bs["main_noN|strat|B2000"]
    s = "% Auto-generated by scripts/make_numbers_tex.py -- do not edit by hand.\n"
    # primary
    s += macro("GamPt", f(P["gamma_point"]))
    s += macro("GamLo", f(P["gamma_ci_lo"]))
    s += macro("GamHi", f(P["gamma_ci_hi"]))
    s += macro("GamFracPos", f"{P['frac_gamma_gt0']:.3f}")
    s += macro("RedPt", f(P["reduction_all6_point"], 2))
    s += macro("RedMed", f(P["reduction_all6_median"], 2))
    s += macro("RedLo", f(P["reduction_all6_ci_lo"], 2))
    s += macro("RedHi", f(P["reduction_all6_ci_hi"], 2))
    s += macro("RedAcc", f"{P['reduction_all6_frac_ge_0.30']:.3f}")
    s += macro("RedThreePt", f(P["reduction_orig3_point"], 3))
    s += macro("RedThreeLo", f(P["reduction_orig3_ci_lo"], 3))
    s += macro("RedThreeHi", f(P["reduction_orig3_ci_hi"], 3))
    s += macro("BootB", str(P["B_requested"]))
    # draft reproduction (main_noN, original two-level bootstrap, B=500)
    s += macro("OrigGamPt", f(O["gamma_point"]))
    s += macro("OrigGamMean", f(O["gamma_boot_mean"]))
    s += macro("OrigGamMed", f(O["gamma_boot_median"]))
    s += macro("OrigGamLo", f(O["gamma_ci_lo"]))
    s += macro("OrigGamHi", f(O["gamma_ci_hi"]))
    s += macro("OrigMissing", str(O["replicates_missing_a_family"]))
    s += macro("OrigThreeMed", f(O["reduction_orig3_median"], 3))
    s += macro("OrigVoneMed", f(O["reduction_v1_median"], 3))
    s += macro("OrigAllSixMed", f(O["reduction_all6_median"], 2))
    s += macro("StatedOrigMissing", str(SO["replicates_missing_a_family"]))
    s += macro("StatedOrigLo", f(SO["gamma_ci_lo"]))
    s += macro("StatedOrigHi", f(SO["gamma_ci_hi"]))
    # sensitivity
    s += macro("IidLo", f(I["gamma_ci_lo"]))
    s += macro("IidHi", f(I["gamma_ci_hi"]))
    s += macro("McLo", f(MC["gamma_ci_lo"]))
    s += macro("McHi", f(MC["gamma_ci_hi"]))
    s += macro("NoNPt", f(MN["gamma_point"]))
    s += macro("NoNLo", f(MN["gamma_ci_lo"]))
    s += macro("NoNHi", f(MN["gamma_ci_hi"]))
    s += macro("QcatPt", f(QC["gamma_point"]))
    s += macro("QcatLo", f(QC["gamma_ci_lo"]))
    s += macro("QcatHi", f(QC["gamma_ci_hi"]))
    s += macro("QcatRedPt", f(QC["reduction_all6_point"], 2))
    s += macro("CellPt", f(CF["gamma_point"]))
    s += macro("CellLo", f(CF["gamma_ci_lo"]))
    s += macro("CellHi", f(CF["gamma_ci_hi"]))
    s += macro("CellRedPt", f(CF["reduction_all6_point"], 2))
    s += macro("OlsPt", f(pe["stated|ols"]["gamma"]))
    s += macro("CellMeansPt", f(pe["stated|cellmeans_wls"]["gamma"]))
    s += macro("QePt", f(pe["stated_qe|wls"]["gamma"]))
    jk = r["jackknife_stated"]
    s += macro("JackLo", f(jk["gamma_range"][0]))
    s += macro("JackHi", f(jk["gamma_range"][1]))
    # diagnostics
    s += macro("WithinShareOneD", pct(dg["share_within_family_SS_ctilde_by_family"]["1D"]))
    s += macro("CellsCtVary", str(dg["cells_ctilde_varies_across_seeds"]))
    s += macro("SeRatioMed", f"{dg['between_seed_sd_over_mean_batch_se']['median']:.3f}")
    s += macro("CtMaxWS", f"{dg['ctilde_max_by_family']['WS']:.3f}")
    s += macro("CtMaxConfig", f"{dg['ctilde_max_by_family']['config']:.3f}")
    # containment brute force
    cb = json.load(open(CB))["summary"]
    s += macro("ContCases", str(cb["cases"]))
    # exact chain
    ex = {(x["n"], x["r"]): x for x in json.load(open(EX))}
    for (n, rr), x in ex.items():
        tag = {9: "Nine", 15: "Fifteen", 17: "Seventeen", 21: "TwentyOne", 23: "TwentyThree", 25: "TwentyFive"}[n]
        s += macro(f"Res{tag}", f"{x['l1_residual']:.1e}".replace("e-", "\\times10^{-") + "}")
    s += macro("ExactMaxResid",
               f"{max(x['l1_residual'] for x in ex.values()):.1e}".replace("e-", "\\times10^{-") + "}")
    # simulations
    if SIM.exists():
        sm = json.load(open(SIM))
        z1 = max(abs(x["z"]) for x in sm["S1_regionII"])
        d1 = max(abs(x["M_sim"] - x["M_exact"]) for x in sm["S1_regionII"])
        s += macro("SimTwoMaxAbsZ", f"{z1:.1f}")
        s += macro("SimTwoMaxAbsDiff", sci(d1))
        s += macro("SimTwoMaxSE", f"{max(x['se'] for x in sm['S1_regionII']):.4f}")
        r1 = sm["S2_S3_regionI"]
        s += macro("SimOneMaxAbsZ", f"{max(abs(x['z_M']) for x in r1):.1f}")
        s += macro("SimOneMaxAbsDiff", sci(max(abs(x['M_sim'] - x['M_band']) for x in r1)))
        s += macro("SimEKMaxAbsZ", f"{max(abs(x['z_EK']) for x in r1):.1f}")
        s += macro("SimCVMaxAbsZ", f"{max(abs(x['z_CV2']) for x in r1):.1f}")
        s += macro("SimReplicas", str(sm["config"]["R"]))
        s += macro("SimEvents", f"{sm['config']['T']:.0e}".replace("e+0", "\\times10^{") + "}")
    nb = ROOT / "data/processed/newborn_test_v2_corrected.csv"
    if nb.exists():
        import pandas as pd
        d = pd.read_csv(nb)
        x = d[(d.ctilde_formula > 0) & (d.ctilde_formula < 1)]
        s += macro("NewbornInterior", str(len(x)))
        s += macro("NewbornMaxZ", f"{x['z'].abs().max():.2f}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(s)
    print(s)
    write_tables(r, ex)


SPEC_LABEL = {"stated": r"stated: lin.\ $q$, $C(n)$",
              "main_noN": r"lin.\ $q$, no $C(n)$",
              "q_cat": r"categ.\ $q$, $C(n)$",
              "nq_cellFE": r"$(n,q)$-cell FE"}
SCHEME_LABEL = {"strat": "stratified cluster", "orig": "unstratified (v2)",
                "iid": "runs iid", "mc_only": "within cells"}


def ci(lo, hi, d=4):
    return f"$[{f(lo, d)},{f(hi, d)}]$"


def write_tables(r, ex):
    bs, pe = r["bootstrap"], r["point_estimates"]
    # main-text Table 2
    order = [("stated", "strat", 2000), ("stated", "orig", 2000), ("stated", "iid", 2000),
             ("stated", "mc_only", 2000), ("main_noN", "strat", 2000),
             ("q_cat", "strat", 2000), ("nq_cellFE", "strat", 2000)]
    rows = []
    for spec, sch, B in order:
        x = bs[f"{spec}|{sch}|B{B}"]
        lab = SCHEME_LABEL[sch] + ("$^\\ast$" if (spec, sch) == ("stated", "strat") else "")
        rows.append(f"{SPEC_LABEL[spec]} & {lab} & ${f(x['gamma_point'])}$ & "
                    f"{ci(x['gamma_ci_lo'], x['gamma_ci_hi'])} & ${f(x['reduction_all6_point'], 2)}$ & "
                    f"{ci(x['reduction_all6_ci_lo'], x['reduction_all6_ci_hi'], 3)}\\\\")
    (ROOT / "manuscript/table2_rows.tex").write_text("\n".join(rows) + "\n\\bottomrule\n")
    # SM Table S2 (all runs)
    rows = []
    for key, x in bs.items():
        spec, sch, Bs = key.split("|")
        dag = r"$^\dagger$" if Bs == "B500" else ""
        rows.append(f"{SPEC_LABEL[spec]}{dag} & {SCHEME_LABEL[sch]} & {x['B_requested']} & "
                    f"${f(x['gamma_point'])}$ & {ci(x['gamma_ci_lo'], x['gamma_ci_hi'])} & "
                    f"{ci(x['reduction_all6_ci_lo'], x['reduction_all6_ci_hi'], 3)} & "
                    f"{x['replicates_missing_a_family']}\\\\")
    for key, lab in (("stated|ols", "stated spec., OLS"),
                     ("stated|cellmeans_wls", "stated spec., 72 cell means")):
        rows.append(f"{lab} & --- & --- & ${f(pe[key]['gamma'])}$ & --- & "
                    f"point ${f(pe[key]['reduction_all6'], 2)}$ & ---\\\\")
    (ROOT / "manuscript/sm_table_s2_rows.tex").write_text("\n".join(rows) + "\n\\bottomrule\n")
    # SM Table S3 (independent solver)
    rows = []
    for (n, rr), x in sorted(ex.items()):
        res = f"{x['l1_residual']:.1e}".replace("e-", r"\times10^{-") + "}"
        dif = f"{x['float_minus_rational']:.1e}".replace("e-", r"\times10^{-") + "}"
        rows.append(f"{n} & {rr} & {x['reachable_full_colourings']} & {x['M_float']:.10f} & "
                    f"${res}$ & ${dif}$\\\\")
    (ROOT / "manuscript/sm_table_s3_rows.tex").write_text("\n".join(rows) + "\n\\bottomrule\n")


if __name__ == "__main__":
    main()
